// Generates plain serializable C# DTOs for Unity from openapi/openapi.yaml.
//   deno run -A scripts/generate-csharp-dtos.ts  → unity-contracts/Generated/ConimeApiDtos.cs
// Field names keep the JSON snake_case names so the classes work with Newtonsoft.Json
// (recommended: com.unity.nuget.newtonsoft-json) without attributes. Enums are emitted
// as strings so unknown future values never break deserialization.
import { parse } from "@std/yaml";

type Schema = Record<string, unknown>;
const root = new URL("..", import.meta.url).pathname;
const doc = parse(await Deno.readTextFile(`${root}openapi/openapi.yaml`)) as { info: { version: string }; components: { schemas: Record<string, Schema> } };
const S = doc.components.schemas;
const classes = new Map<string, string>();
const pascal = (s: string) => s.split(/[_\-\s]/).map((p) => p.charAt(0).toUpperCase() + p.slice(1)).join("");
const SKIP = new Set(["Uuid", "Timestamp", "NullableTimestamp", "NextCursor"]);
const LONG_FIELDS = new Set(["seq", "latest_seq", "last_read_seq", "byte_size", "max_bytes"]);

function refName(ref: string) {
  return ref.split("/").pop()!;
}

function isNullable(s: Schema): boolean {
  if (Array.isArray(s.type) && (s.type as string[]).includes("null")) return true;
  if (Array.isArray(s.oneOf) && (s.oneOf as Schema[]).some((x) => x.type === "null")) return true;
  return false;
}

function typeOf(s: Schema, ctx: string, field: string): string {
  if (s.$ref) {
    const n = refName(s.$ref as string);
    if (n === "Uuid" || n === "Timestamp" || n === "NullableTimestamp" || n === "NextCursor") return "string";
    emit(n, S[n]);
    return n;
  }
  if (Array.isArray(s.oneOf)) {
    const nonNull = (s.oneOf as Schema[]).filter((x) => x.type !== "null");
    if (nonNull.length === 1) return typeOf(nonNull[0], ctx, field);
    return "Newtonsoft.Json.Linq.JToken";
  }
  if (s.allOf) {
    emit(ctx + pascal(field), s);
    return ctx + pascal(field);
  }
  const types = (Array.isArray(s.type) ? s.type : [s.type]).filter((t) => t !== "null") as string[];
  const t = types[0];
  const nullable = isNullable(s);
  switch (t) {
    case "string": return "string";
    case "boolean": return nullable ? "bool?" : "bool";
    case "integer": return (LONG_FIELDS.has(field) ? "long" : "int") + (nullable ? "?" : "");
    case "number": return nullable ? "double?" : "double";
    case "array": return `List<${typeOf((s.items as Schema) ?? {}, ctx, field.replace(/s$/, ""))}>`;
    case "object": {
      if (s.properties) {
        const n = ctx + pascal(field);
        emit(n, s);
        return n;
      }
      if (s.additionalProperties && typeof s.additionalProperties === "object") {
        return `Dictionary<string, ${typeOf(s.additionalProperties as Schema, ctx, field)}>`;
      }
      return "Newtonsoft.Json.Linq.JObject";
    }
    default: return "Newtonsoft.Json.Linq.JToken";
  }
}

function collectProps(s: Schema): { props: Record<string, Schema>; required: string[] } {
  if (s.allOf) {
    const out = { props: {} as Record<string, Schema>, required: [] as string[] };
    for (const part of s.allOf as Schema[]) {
      const p = part.$ref ? collectProps(S[refName(part.$ref as string)]) : collectProps(part);
      Object.assign(out.props, p.props);
      out.required.push(...p.required);
    }
    return out;
  }
  return { props: (s.properties as Record<string, Schema>) ?? {}, required: (s.required as string[]) ?? [] };
}

function emit(name: string, s: Schema) {
  if (classes.has(name) || SKIP.has(name)) return;
  classes.set(name, ""); // reserve (handles recursion)
  const { props, required } = collectProps(s);
  const lines: string[] = [];
  if (s.description) lines.push(`    /// <summary>${String(s.description).split("\n")[0].replace(/[<>&]/g, "")}</summary>`);
  lines.push("    [Serializable]", `    public class ${name}`, "    {");
  for (const [field, ps] of Object.entries(props)) {
    const t = typeOf(ps, name, field);
    const notes: string[] = [];
    if (ps.enum) notes.push(`one of: ${(ps.enum as unknown[]).filter((x) => x !== null).join(", ")} (treat unknown values gracefully)`);
    if (ps.description) notes.push(String(ps.description).split("\n")[0]);
    if (!required.includes(field)) notes.push("optional");
    if (isNullable(ps)) notes.push("nullable");
    if (notes.length) lines.push(`        /// <summary>${notes.join(". ").replace(/[<>&]/g, "")}</summary>`);
    lines.push(`        public ${t} ${field};`);
  }
  lines.push("    }");
  classes.set(name, lines.join("\n"));
}

for (const [name, s] of Object.entries(S)) emit(name, s);

const header = `// <auto-generated>
// Generated by scripts/generate-csharp-dtos.ts from openapi/openapi.yaml (API ${doc.info.version}).
// Do not edit by hand; regenerate when the contract changes.
// Recommended serializer: Newtonsoft.Json (Unity package com.unity.nuget.newtonsoft-json).
// Timestamps are ISO 8601 UTC strings; parse with DateTimeOffset.Parse(value, CultureInfo.InvariantCulture).
// </auto-generated>
// Optional/nullable value types are int?/bool?; reference types are null when absent.
using System;
using System.Collections.Generic;

namespace Conime.Api.Dto
{
${[...classes.values()].filter(Boolean).join("\n\n")}
}
`;
await Deno.mkdir(`${root}unity-contracts/Generated`, { recursive: true });
await Deno.writeTextFile(`${root}unity-contracts/Generated/ConimeApiDtos.cs`, header);
console.log(`generated ${[...classes.values()].filter(Boolean).length} C# DTO classes`);
